  KEY `idx_doi` (`doi`),
  KEY `idx_year` (`publication_year`),
  KEY `idx_source` (`source_title`(191)),
  KEY `idx_pubmed` (`pubmed_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
